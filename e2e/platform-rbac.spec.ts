import { expect, test } from '@playwright/test';
import { mkdirSync } from 'node:fs';

test('Platform management provides role configuration and enforces a monitoring-only account', async ({ page }, testInfo) => {
  test.setTimeout(90_000);
  const auth = await (await page.request.get('/api/auth/status')).json();
  expect((await page.request.post(auth.needsSetup ? '/api/auth/setup' : '/api/auth/login', { data: { username: 'e2e-admin', password: 'test-password' } })).ok()).toBeTruthy();
  await page.request.put('/api/settings', { data: { settings: { statusline_prompted: 'true' } } });
  await page.goto('/');
  await page.getByRole('button', { name: '平台管理', exact: true }).click();
  const dialog = page.getByRole('dialog', { name: '平台管理' });
  const nav = dialog.getByRole('navigation', { name: '平台管理分类' });
  await expect(nav.getByRole('button', { name: '用户管理', exact: true })).toBeVisible();
  await nav.getByRole('button', { name: '角色与权限', exact: true }).click();
  await dialog.getByRole('button', { name: '新建角色', exact: true }).click();
  await dialog.getByLabel('角色名称', { exact: true }).fill('测试观察员');
  await dialog.getByLabel('说明', { exact: true }).fill('仅查看用户监控与平台设置');
  await dialog.getByLabel('用户监控授权级别').selectOption('read');
  await dialog.getByLabel('平台设置授权级别').selectOption('read');
  await dialog.getByRole('button', { name: '保存角色', exact: true }).click();
  await expect(dialog.getByRole('status')).toHaveText('角色已保存');
  await page.screenshot({ path: testInfo.outputPath('platform-role-matrix.png') });
  await nav.getByRole('button', { name: '用户管理', exact: true }).click();
  await dialog.getByRole('button', { name: '新建用户', exact: true }).click();
  await dialog.getByLabel('用户名', { exact: true }).fill('e2e-observer');
  await dialog.getByLabel('显示名称', { exact: true }).fill('测试监控用户');
  await dialog.getByLabel('初始密码', { exact: true }).fill('test-password');
  await dialog.getByRole('button', { name: '创建用户', exact: true }).click();
  await expect(dialog.getByRole('heading', { name: '测试监控用户', exact: true })).toBeVisible();
  await dialog.getByRole('checkbox', { name: '普通成员', exact: true }).uncheck();
  await dialog.getByRole('checkbox', { name: '测试观察员', exact: true }).check();
  await dialog.getByRole('button', { name: '保存角色分配', exact: true }).click();
  const { users } = await (await page.request.get('/api/users')).json();
  const observer = users.find((user: { username: string }) => user.username === 'e2e-observer');
  const { roles } = await (await page.request.get('/api/rbac/roles')).json();
  const observerRole = roles.find((role: { name: string }) => role.name === '测试观察员');
  await expect.poll(async () => (await (await page.request.get('/api/users')).json()).users.find((user: { id: string }) => user.id === observer.id)?.role_ids).toEqual([observerRole.id]);
  await dialog.getByRole('button', { name: '关闭平台管理' }).click();
  await page.request.post('/api/auth/logout');
  expect((await page.request.post('/api/auth/login', { data: { username: 'e2e-observer', password: 'test-password' } })).ok()).toBeTruthy();
  await page.reload();
  await page.getByRole('button', { name: '平台管理', exact: true }).click();
  await expect(nav.getByRole('button', { name: '用户监控', exact: true })).toBeVisible();
  for (const name of ['用户管理', '角色与权限', '项目授权', 'Agent API']) await expect(nav.getByRole('button', { name, exact: true })).toBeHidden();
  await expect(dialog.getByRole('button', { name: /^重命名会话标签/ })).toBeHidden();
  await expect(dialog.getByRole('button', { name: /^删除会话标签/ })).toBeHidden();
  await nav.getByRole('button', { name: '平台设置', exact: true }).click();
  await expect(dialog.getByRole('button', { name: '保存', exact: true })).toBeHidden();
  expect((await page.request.put('/api/settings', { data: { settings: { terminal_font_size: '20' } } })).status()).toBe(403);
  expect((await page.request.get('/api/users')).status()).toBe(403);
  expect((await page.request.get('/api/agent/capabilities')).status()).toBe(403);
  await page.setViewportSize({ width: 390, height: 844 });
  await nav.getByRole('button', { name: '我的账户', exact: true }).click();
  await expect(dialog.getByRole('heading', { name: '修改我的密码', exact: true })).toBeVisible();
  await expect(dialog).toBeVisible();
  await page.screenshot({ path: testInfo.outputPath('platform-mobile-account.png') });
});

test('Project ownership, client selection and monitoring all use compact expandable tables', async ({ page }, testInfo) => {
  test.setTimeout(90_000);
  const status = await (await page.request.get('/api/auth/status')).json();
  const auth = await (await page.request.post(status.needsSetup ? '/api/auth/setup' : '/api/auth/login', { data: { username: 'e2e-admin', password: 'test-password' } })).json();
  const admin = auth.user;
  const { join } = await import('path');
  const projectPath = join(process.cwd(), '.test-data', 'e2e', 'platform-table-project');
  mkdirSync(projectPath, { recursive: true });
  const existing = (await (await page.request.get('/api/projects')).json()).projects.find((project: { path: string }) => project.path === projectPath);
  const project = existing ?? (await (await page.request.post('/api/projects', { data: { name: 'Table Review Project', path: projectPath } })).json()).project;
  const { user: member } = await (await page.request.post('/api/users', { data: { username: 'table-member', password: 'test-password', display_name: '表格测试用户' } })).json();
  const sessionIds: string[] = [];
  try {
    for (const cli_type of ['claude', 'codex']) {
      const { session } = await (await page.request.post('/api/sessions', { data: { project_id: project.id, project_path: projectPath, task: `Table test ${cli_type}`, mode: 'session', cli_type } })).json();
      sessionIds.push(session.id);
    }
    await page.request.put('/api/settings', { data: { settings: { statusline_prompted: 'true' } } });
    await page.request.put('/api/user-state/app', { data: { value: { activeTab: 'home', projectTabs: [{ projectId: project.id, projectName: project.name }] } } });
    await page.request.put(`/api/user-state/${encodeURIComponent(`project:${project.id}`)}`, { data: { value: { terminalInstances: sessionIds.map((id, index) => ({ id, label: `表格会话 ${index + 1}`, customLabel: `表格会话 ${index + 1}` })), activeTerminalId: null, hiddenSessionIds: [], explorerInstances: [], showLauncher: true } } });
    await page.goto('/');
    const projectsTable = page.getByRole('table', { name: '项目列表' });
    await expect(projectsTable.getByRole('columnheader', { name: '所属用户' })).toBeVisible();
    await expect(projectsTable.getByText(`@${admin.username}`, { exact: true }).first()).toBeVisible();
    await expect(projectsTable.getByRole('button', { name: /Agent/, exact: false })).toHaveCount(0);
    await page.screenshot({ path: testInfo.outputPath('compact-projects.png') });
    await page.getByRole('button', { name: '平台管理', exact: true }).click();
    const dialog = page.getByRole('dialog', { name: '平台管理' });
    const nav = dialog.getByRole('navigation', { name: '平台管理分类' });
    await nav.getByRole('button', { name: '项目授权', exact: true }).click();
    await dialog.getByLabel('项目', { exact: true }).selectOption(project.id);
    const grants = dialog.getByRole('table', { name: '项目授权' });
    await expect(grants.getByRole('columnheader')).toHaveText(['用户', 'Session', 'Terminal', '操作']);
    const memberRow = grants.getByRole('row').filter({ hasText: '@table-member' });
    await memberRow.getByRole('button', { name: '配置 table-member 的 Session 客户端' }).click();
    await memberRow.getByRole('checkbox', { name: 'Codex', exact: true }).check();
    await memberRow.getByRole('checkbox', { name: '允许 table-member 使用 Terminal' }).check();
    await memberRow.getByRole('button', { name: '保存', exact: true }).click();
    await expect.poll(async () => (await (await page.request.get(`/api/projects/${project.id}/access`)).json()).access.find((row: { user_id: string }) => row.user_id === member.id)?.session_clients).toEqual(['codex']);
    await page.screenshot({ path: testInfo.outputPath('session-client-permissions.png') });
    await nav.getByRole('button', { name: '用户监控', exact: true }).click();
    await expect(dialog.getByRole('button', { name: `展开用户 ${admin.username}` })).toBeVisible();
    await dialog.getByRole('button', { name: `展开用户 ${admin.username}` }).click();
    await dialog.getByRole('button', { name: `展开项目 ${project.name}` }).click();
    await expect(dialog.getByText('表格会话 1', { exact: true })).toBeVisible();
    const userRow = dialog.getByRole('table', { name: '用户监控', exact: true }).getByRole('row').filter({ has: page.getByRole('button', { name: `收起用户 ${admin.username}` }) }).first();
    const height = (await userRow.boundingBox())?.height ?? 0;
    expect(height).toBeGreaterThan(20); expect(height).toBeLessThan(50);
    await page.screenshot({ path: testInfo.outputPath('compact-monitor-expanded.png') });
    await nav.getByRole('button', { name: '平台设置', exact: true }).click();
    for (const name of ['Agent 会话', '重启服务器']) await expect(dialog.getByRole('button', { name, exact: true })).toBeHidden();
    await expect(dialog.getByText('服务端口', { exact: true })).toBeHidden();
  } finally {
    for (const id of sessionIds) await page.request.delete(`/api/sessions/${id}`);
  }
});
