import {createServer,request as httpRequest} from 'node:http';
import {fork} from 'node:child_process';
import {mkdirSync,lstatSync,chmodSync,unlinkSync} from 'node:fs';
import {createHash} from 'node:crypto';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {fileURLToPath} from 'node:url';
import WebSocket,{WebSocketServer} from 'ws';
import {projectCodexTerminalFrame,terminalHistoryMethods} from './terminal-projection.js';

const VERSION=1,IDLE_MS=60_000;
const preparing=new Map<string,Promise<string>>();
const fingerprint=(upstream:string)=>createHash('sha256').update(JSON.stringify([VERSION,upstream])).digest('hex').slice(0,16);
function inspectBridge(socketPath:string,upstream:string):Promise<'ready'|'missing'|'unavailable'>{
  return new Promise(resolve=>{
    const req=httpRequest({socketPath,path:'/_health',timeout:500},res=>{
      res.on('error',()=>resolve('unavailable'));res.on('aborted',()=>resolve('unavailable'));
      let body='';res.on('data',chunk=>{body+=chunk;if(body.length>512)req.destroy();});res.on('end',()=>{try{const value=JSON.parse(body);resolve(value.version===VERSION&&value.scope===fingerprint(upstream)?'ready':'unavailable');}catch{resolve('unavailable');}});
    });req.on('timeout',()=>req.destroy());req.on('error',(error:NodeJS.ErrnoException)=>resolve(['ENOENT','ECONNREFUSED'].includes(error.code??'')?'missing':'unavailable'));req.end();
  });
}

/** One lazy bridge per engine, shared by all terminal clients. It outlives the
 * dashboard so restarting the platform cannot disconnect a running TUI. No
 * model input or engine lifecycle operation is generated by this process. */
export function ensureCodexTerminalBridge(upstream:string):Promise<string>{
  const pending=preparing.get(upstream);if(pending)return pending;
  const operation=(async()=>{
    // A short private Unix path also fits macOS's sockaddr_un limit.
    const directory=join(tmpdir(),`octo-tui-${process.getuid?.()??'user'}-${fingerprint(upstream)}`),socketPath=join(directory,'t.sock');
    mkdirSync(directory,{recursive:true,mode:0o700});const info=lstatSync(directory);
    if(!info.isDirectory()||info.isSymbolicLink()||process.getuid&&info.uid!==process.getuid())throw Error('原始终端兼容通道目录不可用');
    chmodSync(directory,0o700);
    const state=await inspectBridge(socketPath,upstream);if(state==='ready')return socketPath;
    // A timeout is not evidence of a dead listener. Never unlink the socket of
    // a busy bridge and strand its existing terminal clients.
    if(state==='unavailable')throw Error('原始终端兼容通道暂未响应，请稍后重试');
    try{const stale=lstatSync(socketPath);if(stale.isSocket()&&Date.now()-stale.mtimeMs>10_000)unlinkSync(socketPath);}catch(error:any){if(error.code!=='ENOENT')throw error;}
    const script=fileURLToPath(import.meta.url);
    const child=fork(script,['--codex-terminal-bridge-worker',socketPath,upstream],{
      detached:true,stdio:['ignore','ignore','ignore','ipc'],
      execArgv:script.endsWith('.ts')?['--import',import.meta.resolve('tsx/esm')]:[],
    });
    try{
      await new Promise<void>((resolve,reject)=>{
        const timer=setTimeout(()=>{child.kill();reject(Error('原始终端兼容通道启动超时'));},5000);
        const done=(error?:Error)=>{clearTimeout(timer);child.off('message',message);child.off('error',failed);child.off('exit',exited);error?reject(error):resolve();};
        const message=(value:any)=>{if(value?.type==='ready')done();};
        const failed=()=>done(Error('原始终端兼容通道启动失败'));
        const exited=()=>{void inspectBridge(socketPath,upstream).then(state=>done(state==='ready'?undefined:Error('原始终端兼容通道未就绪')));};
        child.on('message',message);child.once('error',failed);child.once('exit',exited);
      });
      return socketPath;
    }finally{if(child.connected)child.disconnect();child.unref();}
  })();preparing.set(upstream,operation);
  void operation.finally(()=>{if(preparing.get(upstream)===operation)preparing.delete(upstream);}).catch(()=>{});
  return operation;
}

export async function startCodexTerminalBridge(socketPath:string,upstreamPath:string,options:{idleMs?:number;onIdle?:()=>void}={}){
  const server=createServer((req,res)=>{if(req.url!=='/_health'){res.writeHead(404).end();return;}touch();res.setHeader('Content-Type','application/json');res.end(JSON.stringify({version:VERSION,scope:fingerprint(upstreamPath)}));});
  const wss=new WebSocketServer({server,maxPayload:100*1024*1024});
  let idle:ReturnType<typeof setTimeout>|undefined,closed=false,inode:number|undefined;
  function touch(){clearTimeout(idle);if(!closed&&!wss.clients.size){idle=setTimeout(()=>{void stop().then(()=>options.onIdle?.());},options.idleMs??IDLE_MS);idle.unref();}}
  async function stop(){
    if(closed)return;closed=true;clearTimeout(idle);
    for(const client of wss.clients)client.terminate();
    await new Promise<void>(resolve=>wss.close(()=>resolve()));await new Promise<void>(resolve=>server.close(()=>resolve()));
    try{if(lstatSync(socketPath).ino===inode)unlinkSync(socketPath);}catch{}
  }
  wss.on('connection',client=>{
    clearTimeout(idle);client.pause();
    const upstream=new WebSocket(`ws+unix://${upstreamPath}:/`,{maxPayload:100*1024*1024,handshakeTimeout:4000});
    const requests=new Map<string|number,string>();
    const close=()=>{requests.clear();if(client.readyState===WebSocket.OPEN)client.close(1011,'Native terminal connection closed');if(upstream.readyState===WebSocket.CONNECTING)upstream.terminate();else upstream.close();};
    function forward(source:WebSocket,target:WebSocket,data:WebSocket.RawData|string,binary:boolean){
      if(target.readyState!==WebSocket.OPEN){close();return;}
      source.pause();target.send(data,{binary},error=>{if(error)close();else source.resume();});
    }
    client.on('message',(bytes,binary)=>{
      if(!binary)try{const frame=JSON.parse(bytes.toString());if(frame.method&&['string','number'].includes(typeof frame.id)&&terminalHistoryMethods.has(frame.method)){requests.set(frame.id,frame.method);while(requests.size>512)requests.delete(requests.keys().next().value!);}}catch{}
      // Every native request, including attached images and idempotency IDs,
      // goes upstream byte-for-byte. Never retry a request after connection loss.
      forward(client,upstream,bytes,binary);
    });
    upstream.on('message',(bytes,binary)=>{
      let output:WebSocket.RawData|string=bytes;
      if(!binary){const raw=bytes.toString();
        // Ordinary streaming deltas take this fast path without JSON parsing.
        if(requests.size||raw.includes('<send_user_message_question_reply>'))try{
          const frame=JSON.parse(raw),method=!frame.method?requests.get(frame.id):undefined;
          if(!frame.method)requests.delete(frame.id);
          const projected=projectCodexTerminalFrame(frame,method);if(projected!==frame)output=JSON.stringify(projected);
        }catch{}
      }
      forward(upstream,client,output,binary);
    });
    upstream.once('open',()=>client.resume());client.on('error',close);upstream.on('error',close);
    client.once('close',()=>{close();touch();});upstream.once('close',close);
  });
  await new Promise<void>((resolve,reject)=>{server.once('error',reject);server.listen(socketPath,()=>{server.off('error',reject);resolve();});});
  chmodSync(socketPath,0o600);inode=lstatSync(socketPath).ino;touch();
  return {stop};
}

if(process.argv[2]==='--codex-terminal-bridge-worker'){
  void startCodexTerminalBridge(process.argv[3],process.argv[4],{onIdle:()=>process.exit(0)}).then(bridge=>{
    process.send?.({type:'ready'});const stop=()=>void bridge.stop().finally(()=>process.exit(0));process.once('SIGTERM',stop);process.once('SIGINT',stop);
  }).catch(()=>process.exit(1));
}
